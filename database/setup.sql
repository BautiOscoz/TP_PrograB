SET LOCAL search_path TO public;
CREATE TABLE IF NOT EXISTS pais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(20) NOT NULL CHECK (btrim(nombre) <> '')
);
CREATE TABLE IF NOT EXISTS ciudad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (btrim(nombre) <> ''),
    id_pais BIGINT NOT NULL REFERENCES pais(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS estadio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (btrim(nombre) <> ''),
    ciudad BIGINT NOT NULL REFERENCES ciudad(id) ON DELETE RESTRICT
);
LOCK TABLE pais, ciudad, estadio IN SHARE ROW EXCLUSIVE MODE;
-- Case-insensitive natural keys prevent duplicate seed entries.
CREATE UNIQUE INDEX IF NOT EXISTS pais_nombre_unique ON pais (lower(nombre));
CREATE UNIQUE INDEX IF NOT EXISTS ciudad_pais_nombre_unique ON ciudad (id_pais, lower(nombre));
CREATE UNIQUE INDEX IF NOT EXISTS estadio_ciudad_nombre_unique ON estadio (ciudad, lower(nombre));
